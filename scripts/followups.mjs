#!/usr/bin/env node
// The follow-up ledger: one file per open item in docs/follow-ups/.
//
//   node scripts/followups.mjs check            validate entries and every reference to them
//   node scripts/followups.mjs new "<title>"    create the next entry and print its path
//   node scripts/followups.mjs index            rewrite the generated list in the README
//
// An entry is deleted in the commit that finishes it, so an id that is still referenced after
// that fails `check`.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// The tests point this at a scratch repository.
const ROOT =
  process.env.FOLLOWUPS_ROOT ??
  join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "docs/follow-ups");
const README = join(DIR, "README.md");

const FIELDS = {
  priority: ["high", "medium", "low"],
  // What the item is waiting for: a code change, a question answered, a run on a phone,
  // a missing test, another project, or the owner's decision.
  needs: ["fix", "investigation", "device", "test", "upstream", "decision"],
};
const PROSE = /\.md$/;
const CODE = /\.(ts|tsx|mts|cts|mjs|cjs|js|sh|py|yml|yaml|swift|kt)$/;
// Vendored code, and this checker and its tests, which have to spell out what they reject.
const NOT_SCANNED = [
  "scripts/followups.",
  // Held-out evaluation cases quote ledger ids as fixtures of this checker.
  "harness/evaluations/",
  "harness/tests/heldout.",
  ".agents/",
  "app/vendor/",
  "app/modules/bitchat-module/ios/",
  "app/modules/bitchat-module/android/",
];
const ID = /\bF(\d{2,4})\b/g;
const RANGE = /\bF(\d{2,4})\s*(?:–|-|to)\s*F(\d{2,4})\b/g;
// In prose every id is a reference. In code `F11` may be a key or a colour, so an id counts
// only in a comment or beside the words that introduce one.
const CODE_REFERENCE = /(?:^|\s)(?:\/\/|\/\*|\*|#)\s|follow-?up|known gap/i;
// The marker has to open the comment, so prose and quoted source that mention one pass.
const BARE_MARKER = /(?:^|\s)(?:\/\/|\/\*|\*|#)\s*@?(TODO|FIXME|HACK|XXX)\b/i;
const MARKER_WITHOUT_ID = /\bFOLLOWUP\b(?!\(F\d{2,4}\))/;
const LIST_START =
  "<!-- list:start (generated by scripts/followups.mjs index) -->";
const LIST_END = "<!-- list:end -->";
const NEXT_ID = /<!-- next-id: (\d+) -->/;

function readEntries() {
  const entries = [];
  const problems = [];
  for (const name of readdirSync(DIR)) {
    if (!/^F\d+\.md$/.test(name)) continue;
    const where = `docs/follow-ups/${name}`;
    const text = readFileSync(join(DIR, name), "utf8").replaceAll("\r\n", "\n");
    const front = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!front) {
      problems.push(`${where}: no front matter`);
      continue;
    }
    const meta = {};
    for (const line of front[1].split("\n")) {
      const pair = line.match(/^(\w+): (.*)$/);
      if (!pair) continue;
      try {
        meta[pair[1]] = pair[2].startsWith('"') ? JSON.parse(pair[2]) : pair[2];
      } catch {
        problems.push(`${where}: ${pair[1]} is not a valid quoted string`);
      }
    }
    const before = problems.length;
    if (meta.id !== name.replace(".md", ""))
      problems.push(`${where}: id does not match the file name`);
    if (
      typeof meta.title !== "string" ||
      !meta.title ||
      meta.title.length > 120
    )
      problems.push(`${where}: title is missing or over 120 characters`);
    for (const [field, allowed] of Object.entries(FIELDS)) {
      if (!allowed.includes(meta[field]))
        problems.push(
          `${where}: ${field} must be one of ${allowed.join(", ")}`,
        );
    }
    const [what, doneWhen] = front[2].split(/^## Done when$/m);
    if (!what.trim()) problems.push(`${where}: says nothing about the work`);
    if (!doneWhen?.trim()) problems.push(`${where}: has no "## Done when"`);
    if (problems.length === before)
      entries.push({ ...meta, number: Number(name.slice(1, -3)) });
  }
  entries.sort((a, b) => a.number - b.number);
  return { entries, problems };
}

function renderList(entries) {
  const rows = entries.map(
    (e) =>
      `| [${e.id}](${e.id}.md) | ${e.priority} | ${e.needs} | ${e.title.replaceAll("|", "\\|")} |`,
  );
  return [
    "| Id | Priority | Needs | What |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function readReadme() {
  const readme = readFileSync(README, "utf8");
  const start = readme.indexOf(LIST_START);
  const end = readme.indexOf(LIST_END);
  const next = Number(readme.match(NEXT_ID)?.[1]);
  if (start < 0 || end < 0 || !next) {
    throw new Error(
      "docs/follow-ups/README.md has lost its next-id or list markers",
    );
  }
  const withList = (entries) =>
    `${readme.slice(0, start)}${LIST_START}\n\n${renderList(entries)}\n\n${readme.slice(end)}`;
  return { readme, next, withList };
}

function scannedFiles() {
  // NUL-separated, because git quotes a name holding a tab, a newline or a non-ASCII byte.
  const out = execFileSync(
    "git",
    ["ls-files", "-z", "-co", "--exclude-standard"],
    {
      cwd: ROOT,
      encoding: "utf8",
      maxBuffer: 64 << 20,
    },
  );
  return out
    .split("\0")
    .filter(
      (f) =>
        (PROSE.test(f) || CODE.test(f)) &&
        !NOT_SCANNED.some((p) => f.startsWith(p)) &&
        existsSync(join(ROOT, f)),
    );
}

/** Every id a line refers to, with `F50–F53` and `F79 to F83` counted in full. */
function idsIn(line) {
  const ids = new Set();
  for (const [, from, to] of line.matchAll(RANGE)) {
    for (let n = Number(from); n <= Number(to); n++) ids.add(n);
  }
  for (const [, n] of line.matchAll(ID)) ids.add(Number(n));
  return ids;
}

function check() {
  const { entries, problems } = readEntries();
  const open = new Set(entries.map((e) => e.number));
  const { readme, next, withList } = readReadme();

  const highest = entries.at(-1)?.number ?? 0;
  if (next <= highest)
    problems.push(
      `docs/follow-ups/README.md: next-id must be above ${highest}`,
    );
  if (withList(entries) !== readme)
    problems.push(
      "docs/follow-ups/README.md: list is out of date; run `bun run followups index`",
    );

  for (const file of scannedFiles()) {
    const isCode = CODE.test(file);
    const lines = readFileSync(join(ROOT, file), "utf8").split("\n");
    lines.forEach((line, i) => {
      const at = `${file}:${i + 1}`;
      if (!isCode || CODE_REFERENCE.test(line)) {
        for (const n of idsIn(line)) {
          if (!open.has(n))
            problems.push(`${at}: F${n} is not an open follow-up`);
        }
      }
      if (!isCode) return;
      const marker = line.match(BARE_MARKER);
      if (marker)
        problems.push(
          `${at}: bare ${marker[1]}; write FOLLOWUP(F<n>) and add the entry, or just do it`,
        );
      if (MARKER_WITHOUT_ID.test(line))
        problems.push(`${at}: FOLLOWUP needs an id, as FOLLOWUP(F<n>)`);
    });
  }

  if (problems.length) {
    console.error(problems.join("\n"));
    console.error(
      `\n${problems.length} follow-up problem(s). See docs/follow-ups/README.md.`,
    );
    process.exit(1);
  }
  console.log(`${entries.length} open follow-ups; every reference resolves.`);
}

function create(title) {
  if (!title)
    throw new Error('usage: followups new "<what is left, in one line>"');
  const { readme, next } = readReadme();
  const id = `F${next}`;
  if (existsSync(join(DIR, `${id}.md`)))
    throw new Error(`${id} already exists; correct next-id in the README`);
  const body = `---\nid: ${id}\ntitle: ${JSON.stringify(title)}\npriority: medium\nneeds: fix\n---\n\nWhat is wrong or missing, where (name the file and symbol, not a line number), and why it was\nleft.\n\n## Done when\n\nThe observable result that lets someone delete this file.\n`;
  writeFileSync(join(DIR, `${id}.md`), body);
  writeFileSync(
    README,
    readme.replace(NEXT_ID, `<!-- next-id: ${next + 1} -->`),
  );
  index();
  console.log(`docs/follow-ups/${id}.md`);
}

function index() {
  const { entries, problems } = readEntries();
  if (problems.length) throw new Error(problems.join("\n"));
  writeFileSync(README, readReadme().withList(entries));
}

const commands = { check, index, new: (rest) => create(rest.join(" ")) };
const [name = "check", ...rest] = process.argv.slice(2);
try {
  if (!commands[name])
    throw new Error('usage: followups check | index | new "<title>"');
  commands[name](rest);
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
