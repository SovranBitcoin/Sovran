export function caseById(id: string) {
  const found = cases.find(c => c.id === id);
  if (!found) throw new Error(`Unknown case ${id}`);
  return found;
}

if (import.meta.main) {
  const [command, id, path] = process.argv.slice(2);
  if (command === 'prepare' && id && path) { mkdirSync(path, { recursive: true }); caseById(id).prepare(path); console.log(path); }
  else if (command === 'grade' && id && path) {
    const c = caseById(id);
    const input = c.kind === 'review' ? { dir: '', assessment: JSON.parse(readFileSync(path, 'utf8')) as Assessment } : { dir: path };
    console.log(JSON.stringify({ case: id, ...c.grade(input) }, null, 2));
  } else throw new Error('Usage: bun harness/evaluations/heldout.ts prepare|grade <case> <path>');
}
