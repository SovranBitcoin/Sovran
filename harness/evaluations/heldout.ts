// Held-out full-send evaluation cases (F163), built from real Sovran history at pinned commits.
// Each workspace is a scratch repository whose only history is the case itself, so a worker
// cannot read the answer from later commits. The trusted host still lets a determined worker
// open the real checkout; prompts forbid it and results must say whether it happened.
// Development cases stay in /tmp/sovran-harness/evaluations/development and never appear here.
import { execFileSync, spawnSync } from 'node:child_process';
