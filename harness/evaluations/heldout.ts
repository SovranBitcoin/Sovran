const README = '# Follow-ups\n\n<!-- next-id: 14 -->\n\n<!-- list:start (generated by scripts/followups.mjs index) -->\n<!-- list:end -->\n';
const entry = (id: string, title?: string) =>
  `---\nid: ${id}\n${title ? `title: ${JSON.stringify(title)}\n` : ''}status: open\npriority: low\nneeds: fix\n---\n\nWhat is wrong.\n\n## Done when\n\nIt is right.\n`;

/** Run a candidate checker in a fresh ledger; the script finds its root from its own location. */
function runChecker(script: string, files: Record<string, string>) {
  const root = mkdtempSync(join(tmpdir(), 'heldout-ledger-'));
  try {
    git(root, 'init', '-q');
    write(root, { 'scripts/followups.mjs': script, 'docs/follow-ups/README.md': README, 'docs/follow-ups/F12.md': entry('F12', 'Something is left'), ...files });
    const run = (command: string) => {
      const r = spawnSync('node', [join(root, 'scripts/followups.mjs'), command], { encoding: 'utf8', timeout: 20_000 });
      return { code: r.status, text: `${r.stdout}${r.stderr}` };
    };
    run('index');
    return run('check');
  } finally { rmSync(root, { recursive: true, force: true }); }
}

function gradeUntitled(script: string) {
  const reasons: string[] = [];
  const broken = runChecker(script, { 'docs/follow-ups/F13.md': entry('F13'), 'notes.md': 'See F12 and F99.\n' });
  if (broken.code !== 1) reasons.push(`untitled entry: exit ${broken.code}, expected 1`);
  if (!/F13\.md: title is missing/.test(broken.text)) reasons.push('untitled entry is not reported by name');
  if (!/notes\.md:1: F99 is not an open follow-up/.test(broken.text)) reasons.push('other problems are no longer reported');
  if (/TypeError|\n\s+at /.test(broken.text)) reasons.push('check still crashes with a stack trace');
  const valid = runChecker(script, { 'notes.md': 'See F12.\n' });
  if (valid.code !== 0) reasons.push(`valid ledger: exit ${valid.code}: ${valid.text.slice(0, 200)}`);
  return { pass: !reasons.length, reasons };
}

// --- review graders: verdict plus the specific defect, not a generic objection ----------------
const said = (a: Assessment) => [a.summary, ...a.findings.map(f => f.detail)].join('\n');
const rejects = (pattern: RegExp) => ({ assessment }: { assessment?: Assessment }) => {
  const reasons: string[] = [];
  if (!assessment) return { pass: false, reasons: ['no assessment'] };
  if (assessment.verdict !== 'fail') reasons.push(`verdict ${assessment.verdict}, expected fail`);
  if (!pattern.test(said(assessment))) reasons.push('the defect the case plants is not named');
  return { pass: !reasons.length, reasons };
};

function reviewWorkspace(dir: string, base: Record<string, string>, candidate: Record<string, string>, message: string) {
  git(dir, 'init', '-q');
  write(dir, base); git(dir, 'add', '-A'); git(dir, 'commit', '-qm', 'Base');
  write(dir, candidate); git(dir, 'add', '-A'); git(dir, 'commit', '-qm', message);
}
